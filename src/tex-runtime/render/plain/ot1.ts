/**
 * OT1（Computer Modern 文本字体的编码）码位 → Unicode。
 * 0x12..0x18 的重音与 0x19..0x1F 的字母对应 plain.tex 里的
 * `\accent18..24` 与 `\ss \ae \oe \o \AE \OE \O`。
 */

/** 0x00..0x0F：大写希腊 + 连字 */
const LOW = [
  0x393,
  0x394,
  0x398,
  0x39b,
  0x39e,
  0x3a0,
  0x3a3,
  0x3a5,
  0x3a6,
  0x3a8,
  0x3a9, // Γ Δ Θ Λ Ξ Π Σ Υ Φ Ψ Ω
  0xfb00,
  0xfb01,
  0xfb02,
  0xfb03,
  0xfb04, // ﬀ ﬁ ﬂ ﬃ ﬄ
]

/** 0x10..0x1F：点无字母、重音、变音字母 */
const MID = [
  0x131,
  0x237, // ı ȷ
  0x60,
  0xb4,
  0x2c7,
  0x2d8,
  0xaf,
  0x2da,
  0xb8, // ` ´ ˇ ˘ ¯ ˚ ¸
  0xdf,
  0xe6,
  0x153,
  0xf8,
  0xc6,
  0x152,
  0xd8, // ß æ œ ø Æ Œ Ø
]

/** 0x20..0x7F 里与 ASCII 不同的码位（文本字体用引号类字形代替 < > \ 等） */
const ASCII_OVERRIDES: Record<number, number> = {
  0x22: 0x201d, // ”：`''` 的连字结果
  0x27: 0x2019, // ' 排版上是右单引号
  0x3c: 0xa1, // ¡
  0x3e: 0xbf, // ¿
  0x5c: 0x201c, // “（文本字体里没有反斜杠）
  0x5e: 0x2c6, // ˆ
  0x5f: 0x2d9, // ˙
  0x60: 0x2018, // ‘
  0x7b: 0x2013, // –
  0x7c: 0x2014, // —
  0x7d: 0x2dd, // ˝
  0x7e: 0x2dc, // ˜
  0x7f: 0xa8, // ¨
}

export function ot1ToUnicode(code: number): number | undefined {
  if (code < 0x10) {
    return LOW[code]
  }
  if (code < 0x20) {
    return MID[code - 0x10]
  }
  if (code < 0x80) {
    return ASCII_OVERRIDES[code] ?? code
  }
  return undefined
}
