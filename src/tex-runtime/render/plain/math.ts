/**
 * 数学字体（cmmi10 / cmsy10 / cmex10）码位 → Unicode。
 * 码位取自 plain.tex 的 `\mathchardef`（字体 1 = cmmi10、2 = cmsy10、3 = cmex10，
 * 字体 0 = cmr10 即上面的 OT1）；第一版只覆盖常用码位，其余码位不映射。
 */

function range(start: number, first: number, count: number): Record<number, number> {
  const table: Record<number, number> = {}
  for (let i = 0; i < count; i++) {
    table[start + i] = first + i
  }
  return table
}

